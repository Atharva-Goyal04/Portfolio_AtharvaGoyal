import { readFile, writeFile, mkdir } from 'fs/promises'
import { existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const OUT = join(ROOT, 'src/data/projects.metadata.mjs')

const DEFAULT_CAMERA = 'Sony a7 IV'
const META_URL = process.env.META_URL || ''

function parseCsv(text) {
  const rows = []
  const lines = text.replace(/\r/g, '').split('\n')
  for (const line of lines) {
    if (!line.trim()) continue
    const cols = []
    let cur = ''
    let inQ = false
    for (let i = 0; i < line.length; i++) {
      const c = line[i]
      if (inQ) {
        if (c === '"') {
          if (line[i + 1] === '"') { cur += '"'; i++ } else inQ = false
        } else cur += c
      } else if (c === '"') {
        inQ = true
      } else if (c === ',') {
        cols.push(cur); cur = ''
      } else {
        cur += c
      }
    }
    cols.push(cur)
    rows.push(cols)
  }
  return rows
}

function slugKey(folder, name) {
  return `${folder}/${name}`
}

function normalizeDate(value) {
  const v = (value || '').trim()
  if (!v) return ''
  const m = v.match(/^(\d{4})-(\d{2})/)
  if (m) return `${m[1]}-${m[2]}`
  const y = v.match(/^(\d{4})/)
  if (y) return y[1]
  return v
}

async function main() {
  let csvText = ''
  if (META_URL) {
    try {
      const res = await fetch(META_URL)
      if (!res.ok) throw new Error(`HTTP ${res.status}`)
      csvText = await res.text()
      console.log(`→ Fetched metadata CSV from sheet (${csvText.split('\n').length} lines)`)
    } catch (err) {
      console.warn(`⚠️  Could not fetch metadata URL (${err.message}); keeping last-good metadata.`)
      process.exit(0)
    }
  } else {
    const local = join(ROOT, 'metadata.csv')
    if (existsSync(local)) {
      csvText = await readFile(local, 'utf8')
      console.log(`→ Read local metadata.csv (${csvText.split('\n').length} lines)`)
    } else {
      console.log('ℹ️  No metadata source (META_URL or metadata.csv). Skipping metadata import.')
      process.exit(0)
    }
  }

  const rows = parseCsv(csvText)
  if (!rows.length) {
    console.log('ℹ️  Metadata CSV is empty. Skipping.')
    process.exit(0)
  }

  const headers = rows[0].map((h) => h.trim().toLowerCase())
  const col = (h) => headers.indexOf(h)

  const idxFolderName = Math.max(col('folder/name'), col('folder/name'), col('folder_name'), col('key'), col('image'))
  const idxCamera = col('camera')
  const idxLocation = col('location')
  const idxDate = col('date')

  const metadata = {}
  let matched = 0
  let blankRows = 0

  for (const row of rows.slice(1)) {
    if (row.length < 1) continue
    const key = idxFolderName >= 0 ? (row[idxFolderName] || '').trim() : ''
    if (!key) { blankRows++; continue }

    const camera = idxCamera >= 0 ? (row[idxCamera] || '').trim() : ''
    const location = idxLocation >= 0 ? (row[idxLocation] || '').trim() : ''
    const date = idxDate >= 0 ? normalizeDate(row[idxDate]) : ''

    metadata[key] = {}
    if (camera) metadata[key].camera = camera
    if (location) metadata[key].location = location
    if (date) metadata[key].date = date
    matched++
  }

  await mkdir(dirname(OUT), { recursive: true })
  const output =
    `// AUTO-GENERATED by scripts/import-metadata.mjs — do not edit by hand.\n` +
    `// Source: Google Sheet (published CSV) or local metadata.csv.\n` +
    `// DEFAULT_CAMERA applies when a photo has no camera override.\n` +
    `export const DEFAULT_CAMERA = ${JSON.stringify(DEFAULT_CAMERA)}\n\n` +
    `export const projectMetadata = ${JSON.stringify(metadata, null, 2)}\n`
  await writeFile(OUT, output)

  console.log(`✓ Wrote metadata for ${matched} photos (camera default: ${DEFAULT_CAMERA})`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
